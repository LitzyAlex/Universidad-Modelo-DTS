public struct Estadisticas
{
    public int  VidaMax;
    public int VidaActual;
    public int Ataque; 
    public int Defensa;

    public Estadisticas(int VidaMax, int VidaActual, int Ataque, int Defensa)
    {
        this.VidaMax = VidaMax;
        this.VidaActual = VidaActual;
        this.Ataque = Ataque;
        this.Defensa = Defensa;
    }
}